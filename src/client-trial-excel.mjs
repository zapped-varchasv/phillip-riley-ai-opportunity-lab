import ExcelJS from 'exceljs';
import {clientCriteria,importClientTrial,validSelection,rankClients} from '../dist/client-trial-model.mjs';

const navy='173B48',muted='52677B';
// This is a dated report, not an editable scoring model. Results come from the
// same validated assessment model as the website; no user text becomes a formula.
export function createTrialWorkbook(input,{exportedAt=new Date()}={}){
 const data=importClientTrial(input);
 if(!validSelection(data.selected)||!data.clients.length)throw new Error('Choose 10 criteria and add a client before exporting.');
 const rows=rankClients(data),workbook=new ExcelJS.Workbook();
 workbook.creator='Phillip Riley Team Workspace';workbook.title='Client prioritisation trial';workbook.created=exportedAt;workbook.modified=exportedAt;
 const stamp=exportedAt.toISOString();
 function sheet(name,title,notes,headers,widths){
  const ws=workbook.addWorksheet(name,{views:[{state:'frozen',ySplit:6,showGridLines:false}],pageSetup:{orientation:'landscape',paperSize:9,fitToPage:true,fitToWidth:1,fitToHeight:0,printTitlesRow:'1:6'}});
  widths.forEach((width,i)=>{ws.getColumn(i+1).width=width;});
  ws.getCell('A1').value=title;ws.getCell('A1').font={name:'Arial',size:16,bold:true,color:{argb:navy}};ws.getRow(1).height=28;
  // Context spans otherwise empty cells for legibility; data headers stay unmerged.
  for(const [i,text]of [`Exported ${stamp} · snapshot of current trial inputs`,...notes].entries()){
   ws.mergeCells(i+2,1,i+2,headers.length);ws.getCell(i+2,1).value=text;ws.getCell(i+2,1).font={name:'Arial',size:10,color:{argb:muted}};ws.getCell(i+2,1).alignment={vertical:'middle',wrapText:true};ws.getRow(i+2).height=30;
  }
  ws.getRow(6).values=headers;ws.getRow(6).height=30;
  ws.getRow(6).eachCell(c=>{c.fill={type:'pattern',pattern:'solid',fgColor:{argb:navy}};c.font={name:'Arial',size:10,bold:true,color:{argb:'FFFFFF'}};c.alignment={vertical:'middle',horizontal:'center',wrapText:true};});
  ws.headerFooter.oddFooter='&LPhillip Riley | Client prioritisation&RPage &P of &N';
  return ws;
 }
 function add(ws,values){
  const row=ws.addRow(values);let height=30;
  row.eachCell({includeEmpty:true},(cell,col)=>{
   cell.font={name:'Arial',size:10,color:{argb:'203D55'}};cell.alignment={vertical:'top',wrapText:true,horizontal:typeof cell.value==='number'?'right':'left'};
   if(row.number%2===1)cell.fill={type:'pattern',pattern:'solid',fgColor:{argb:'F2F7F8'}};
   const text=String(cell.value??''),width=Math.max(8,ws.getColumn(col).width-3);
   const lines=text.split('\n').reduce((sum,line)=>sum+Math.max(1,Math.ceil(line.length/width)),0);
   height=Math.max(height,lines*14+12);
  });
  row.height=Math.min(409,height);return row;
 }
 function finish(ws){ws.autoFilter={from:{row:6,column:1},to:{row:ws.rowCount,column:ws.columnCount}};}
 const complete=rows.filter(r=>r.complete);
 const summary=sheet('Priority list','Client priority list',[
  `${rows.length} clients · ${complete.length} ranked · ${rows.length-complete.length} need review. Highest total first; tied totals share a rank.`,
  'A: 80–100 | B: 60–79 | C: below 60. Ten equal-weight scores, each 0–10; total /100 also equals percentage.',
  'Snapshot only: editing Excel will not recalculate or update the site. Change inputs on the site and export again. Use JSON Download worksheet to resume work.'
 ],['Priority','Client','Total /100','Category','Scores completed /10','Reviewer / role','Next action','Last assessed (UTC)'],[12,30,16,18,18,27,90,26]);
 for(const r of rows){
  const c=r.client,row=add(summary,[r.rank,c.name||'Unnamed client',r.total,r.category||'Needs review',r.scored,c.reviewer||null,c.next||null,c.updatedAt||null]);
  const fill={A:'D7F3E7',B:'E1EDFF',C:'FFF0D7'}[r.category]||'EDF1F5';
  row.getCell(4).fill={type:'pattern',pattern:'solid',fgColor:{argb:fill}};row.getCell(4).font={name:'Arial',size:10,bold:true,color:{argb:navy}};
 }finish(summary);
 const scores=sheet('Scores and evidence','Scores and evidence',[
  'One row per client and selected criterion. Blank score means unknown; 0 is an assessed score.',
  'Only the currently applied 10 criteria feed this report. Retained scores for unselected criteria are excluded.',
  'Staff-entered assessments and evidence references; not independently verified or generated by AI.'
 ],['Client','Criterion','Score /10','Evidence / reason'],[30,58,16,110]);
 for(const {client:c}of rows)for(const id of data.selected)add(scores,[c.name||'Unnamed client',clientCriteria.find(k=>k.id===id).label,c.scores[id]??null,c.evidence[id]||null]);
 finish(scores);
 const criteria=sheet('Criteria and method','Criteria and scoring method',[
  'Source: client-quality slides supplied for this trial. Selected criteria reflect the applied choices at export time.',
  '0 = does not meet; 5 = partly meets; 10 = fully meets. Unknown stays blank. All ten must be scored before a client is ranked.',
  'Working thresholds close the source slide’s gap at 59%; confirm with the team. Low categories prompt review, not automatic client rejection.'
 ],['Selected','Scoring order','Criterion','Guidance'],[14,16,58,100]);
 for(const c of clientCriteria){const index=data.selected.indexOf(c.id);add(criteria,[index>=0?'Yes':'No',index>=0?index+1:null,c.label,c.help]);}
 finish(criteria);
 return workbook;
}
export async function trialExcelBytes(data,options){return createTrialWorkbook(data,options).xlsx.writeBuffer();}
